/**
 * Runs after `next build` (static export to out/). Cloudflare Workers static
 * assets read out/_redirects and out/_headers; this writes the parts that
 * depend on the hook list:
 *
 * - /use-debounce.md -> /md/use-debounce as a 200 rewrite (was rewrites() in
 *   next.config.ts, which an export ignores). One line per hook, taken from the
 *   files the export wrote to out/md/.
 * - Headers the Next route handlers used to send, since an export keeps only
 *   the body: Markdown and image content types for the extensionless files,
 *   noindex + canonical Link on the .md copies, CORS on the registry JSON.
 *
 * public/_headers holds the static rules; this script appends to the copy in out/.
 */
import { appendFileSync, existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'out');
const site = 'https://react-hooks.danixsoft.com';

const mdDir = join(out, 'md');
if (!existsSync(mdDir)) throw new Error('out/md is missing: run `next build` (output: export) first.');
const slugs = readdirSync(mdDir, { withFileTypes: true })
  .filter((e) => e.isFile() && /^use-[a-z-]+$/.test(e.name))
  .map((e) => e.name)
  .sort();
if (slugs.length === 0) throw new Error('No hook Markdown files in out/md.');

writeFileSync(
  join(out, '_redirects'),
  [
    '# Generated by scripts/write-cf-routing.mjs: plain-Markdown hook pages.',
    ...slugs.map((slug) => `/${slug}.md /md/${slug} 200`),
    '',
  ].join('\n'),
);

const md = (path, slug) => [
  path,
  '  Content-Type: text/markdown; charset=utf-8',
  '  Cache-Control: public, max-age=3600, s-maxage=86400',
  '  X-Robots-Tag: noindex',
  `  Link: <${site}/${slug}>; rel="canonical"`,
];

appendFileSync(
  join(out, '_headers'),
  [
    '',
    '# Generated by scripts/write-cf-routing.mjs.',
    ...slugs.flatMap((slug) => [...md(`/${slug}.md`, slug), ...md(`/md/${slug}`, slug)]),
    '/og/*',
    '  Content-Type: image/png',
    '/r/*',
    '  Access-Control-Allow-Origin: *',
    '  Cache-Control: public, max-age=3600, s-maxage=86400',
    '',
  ].join('\n'),
);

console.log(`Wrote Cloudflare routing for ${slugs.length} hooks.`);
